"""
3D Wavefront OBJ Exporter for Young's Double-Slit Experiment.
Exports complete 3D laboratory scene:
- Laser / particle gun housing
- Barrier plate with physical dual slit apertures (d and a)
- Detector screen with UV mapping and high-resolution fringe texture
- 3D ray trajectory tubes (r1, r2)
- Which-Way observer detector modules
Generates companion .mtl material library and .png screen texture.
Can be opened in Blender, Windows 3D Viewer, MeshLab, Autodesk AutoCAD, etc.
"""

import os
from typing import Dict, Any, Tuple
import numpy as np
from PIL import Image

from utils.color_utils import ColorUtils

class ObjExporter:
    """Exports 3D simulation geometry to industry-standard Wavefront OBJ + MTL + PNG texture."""

    @classmethod
    def export_scene_to_obj(
        cls,
        filepath: str,
        wavelength_nm: float,
        slit_distance_mm: float,
        slit_width_mm: float,
        screen_distance_m: float,
        which_way_active: bool,
        intensity_1d: np.ndarray,
        base_rgb: Tuple[int, int, int]
    ) -> Dict[str, Any]:
        """
        Exports the 3D scene to an OBJ file, companion MTL file, and screen texture PNG.
        """
        try:
            base_dir = os.path.dirname(filepath)
            base_name = os.path.splitext(os.path.basename(filepath))[0]

            obj_path = os.path.join(base_dir, f"{base_name}.obj")
            mtl_path = os.path.join(base_dir, f"{base_name}.mtl")
            texture_filename = f"{base_name}_screen_texture.png"
            texture_path = os.path.join(base_dir, texture_filename)

            # 1. Synthesize and save high-resolution 2D fringe texture (1024 x 512)
            tex_w, tex_h = 1024, 512
            img_array = ColorUtils.generate_screen_image_array(
                intensity_1d=intensity_1d,
                base_rgb=base_rgb,
                height=tex_h,
                width=tex_w
            )
            pil_img = Image.fromarray(img_array)
            pil_img.save(texture_path)

            # 2. Write Material Template Library (.mtl)
            r_norm = base_rgb[0] / 255.0
            g_norm = base_rgb[1] / 255.0
            b_norm = base_rgb[2] / 255.0

            with open(mtl_path, "w", encoding="utf-8") as f_mtl:
                f_mtl.write(f"# Material Library for {base_name}.obj\n")
                f_mtl.write("# Generated by Thomas Young Double-Slit Simulator\n\n")

                # Source Material
                f_mtl.write("newmtl Material_Source\n")
                f_mtl.write("Ka 0.1 0.1 0.15\n")
                f_mtl.write("Kd 0.15 0.20 0.28\n")
                f_mtl.write("Ks 0.4 0.4 0.4\n")
                f_mtl.write("Ns 60.0\n")
                f_mtl.write("d 1.0\n\n")

                # Barrier Material (Matte metallic)
                f_mtl.write("newmtl Material_Barrier\n")
                f_mtl.write("Ka 0.1 0.1 0.1\n")
                f_mtl.write("Kd 0.22 0.25 0.30\n")
                f_mtl.write("Ks 0.2 0.2 0.2\n")
                f_mtl.write("Ns 30.0\n")
                f_mtl.write("d 1.0\n\n")

                # Screen Material with texture map
                f_mtl.write("newmtl Material_Screen\n")
                f_mtl.write("Ka 0.2 0.2 0.2\n")
                f_mtl.write("Kd 0.9 0.9 0.9\n")
                f_mtl.write("Ks 0.1 0.1 0.1\n")
                f_mtl.write("Ns 10.0\n")
                f_mtl.write(f"map_Kd {texture_filename}\n\n")

                # Laser Beam Material
                f_mtl.write("newmtl Material_Beam\n")
                f_mtl.write(f"Kd {r_norm:.3f} {g_norm:.3f} {b_norm:.3f}\n")
                f_mtl.write(f"Ke {r_norm:.3f} {g_norm:.3f} {b_norm:.3f}\n")
                f_mtl.write("d 0.75\n\n")

                # Ray 1 Material (Emerald)
                f_mtl.write("newmtl Material_Ray1\n")
                f_mtl.write("Kd 0.0 0.9 0.46\n")
                f_mtl.write("Ke 0.0 0.9 0.46\n")
                f_mtl.write("d 0.85\n\n")

                # Ray 2 Material (Gold)
                f_mtl.write("newmtl Material_Ray2\n")
                f_mtl.write("Kd 1.0 0.84 0.0\n")
                f_mtl.write("Ke 1.0 0.84 0.0\n")
                f_mtl.write("d 0.85\n\n")

                # Detector Material
                f_mtl.write("newmtl Material_Detector\n")
                f_mtl.write("Kd 0.93 0.10 0.15\n")
                f_mtl.write("Ke 0.80 0.05 0.10\n")
                f_mtl.write("d 1.0\n\n")

            # 3. Write Wavefront OBJ file
            with open(obj_path, "w", encoding="utf-8") as f_obj:
                f_obj.write(f"# Wavefront OBJ: {base_name}.obj\n")
                f_obj.write("# Thomas Young Double-Slit Experiment Simulator 3D Model\n")
                f_obj.write(f"mtllib {os.path.basename(mtl_path)}\n\n")

                # Calibrated Visual Scale matching the 3D Setup View inside the application
                L = max(screen_distance_m, 0.5)
                y_span = 0.18 * L
                z_span = 0.14 * L
                x_src = -0.22 * L
                src_len = 0.08 * L
                src_half_y = 0.035 * L
                src_half_z = 0.035 * L

                # Slit geometric placement in visual coordinates
                d_normalized = float(np.clip(slit_distance_mm / 0.25, 0.4, 2.2))
                d_cad = 0.05 * L * d_normalized
                half_d = d_cad / 2.0
                y_s1 = -half_d
                y_s2 = +half_d
                # Aperture opening derived from the physical slit width, using
                # the same 0.2*L-per-mm visual scale as d_cad above and the
                # same 0.1 mm visibility floor as the in-app 3D view.
                a_visual_mm = max(float(slit_width_mm), 0.1)
                half_a = min(a_visual_mm * 0.5 * (0.05 * L / 0.25), half_d * 0.8)
                slit_h = 0.08 * L
                t_bar = 0.006 * L

                r_beam = 0.0022 * L
                r_ray = 0.0030 * L

                v_idx = 1
                vt_idx = 1

                # Helper to write a 3D box
                def write_box(name, x_min, x_max, y_min, y_max, z_min, z_max, mtl_name):
                    nonlocal v_idx
                    f_obj.write(f"o {name}\n")
                    f_obj.write(f"usemtl {mtl_name}\n")
                    pts = [
                        (x_min, y_min, z_min), (x_max, y_min, z_min),
                        (x_max, y_max, z_min), (x_min, y_max, z_min),
                        (x_min, y_min, z_max), (x_max, y_min, z_max),
                        (x_max, y_max, z_max), (x_min, y_max, z_max)
                    ]
                    for px, py, pz in pts:
                        f_obj.write(f"v {px:.6f} {py:.6f} {pz:.6f}\n")

                    # 6 faces (each with 4 vertices)
                    base = v_idx
                    faces = [
                        (base, base+1, base+2, base+3), # Bottom
                        (base+4, base+7, base+6, base+5), # Top
                        (base, base+4, base+5, base+1), # Front
                        (base+2, base+6, base+7, base+3), # Back
                        (base, base+3, base+7, base+4), # Left
                        (base+1, base+5, base+6, base+2)  # Right
                    ]
                    for f in faces:
                        f_obj.write(f"f {f[0]} {f[1]} {f[2]} {f[3]}\n")
                    v_idx += 8
                    f_obj.write("\n")

                # Helper to write an oriented 3D cylinder/tube
                def write_cylinder(name, p1, p2, radius, mtl_name, segments=8):
                    nonlocal v_idx
                    p1 = np.array(p1, dtype=float)
                    p2 = np.array(p2, dtype=float)
                    vec = p2 - p1
                    height = float(np.linalg.norm(vec))
                    if height < 1e-9:
                        return
                    dir_u = vec / height
                    ref = np.array([1.0, 0.0, 0.0]) if abs(dir_u[0]) < 0.9 else np.array([0.0, 1.0, 0.0])
                    u = np.cross(dir_u, ref)
                    u /= np.linalg.norm(u)
                    w = np.cross(dir_u, u)

                    angles = np.linspace(0.0, 2.0 * np.pi, segments, endpoint=False)
                    f_obj.write(f"o {name}\n")
                    f_obj.write(f"usemtl {mtl_name}\n")

                    # Vertices at base and top
                    for ang in angles:
                        radial = radius * (np.cos(ang) * u + np.sin(ang) * w)
                        pt = p1 + radial
                        f_obj.write(f"v {pt[0]:.6f} {pt[1]:.6f} {pt[2]:.6f}\n")
                    for ang in angles:
                        radial = radius * (np.cos(ang) * u + np.sin(ang) * w)
                        pt = p2 + radial
                        f_obj.write(f"v {pt[0]:.6f} {pt[1]:.6f} {pt[2]:.6f}\n")

                    base = v_idx
                    # Lateral quads
                    for i in range(segments):
                        nxt = (i + 1) % segments
                        f_obj.write(f"f {base + i} {base + nxt} {base + segments + nxt} {base + segments + i}\n")

                    # Cap polygons
                    cap1 = " ".join(str(base + i) for i in reversed(range(segments)))
                    f_obj.write(f"f {cap1}\n")
                    cap2 = " ".join(str(base + segments + i) for i in range(segments))
                    f_obj.write(f"f {cap2}\n\n")

                    v_idx += 2 * segments

                # A. Laser / Particle Gun Housing
                write_box("Source_Housing", x_src - src_len, x_src, -src_half_y, src_half_y, -src_half_z, src_half_z, "Material_Source")

                # B. Incident Laser Beams (from source aperture to slits)
                write_cylinder("Source_Beam_To_S1", [x_src, 0.0, 0.0], [-t_bar, y_s1, 0.0], r_beam, "Material_Beam")
                write_cylinder("Source_Beam_To_S2", [x_src, 0.0, 0.0], [-t_bar, y_s2, 0.0], r_beam, "Material_Beam")

                # C. Double Slit Barrier Plate (5 clean disjoint non-overlapping panels)
                # 1. Left Wing
                write_box("Barrier_LeftWing", -t_bar, 0.0, -y_span, y_s1 - half_a, -z_span, z_span, "Material_Barrier")
                # 2. Central Septum between slits
                write_box("Barrier_CenterSeptum", -t_bar, 0.0, y_s1 + half_a, y_s2 - half_a, -z_span, z_span, "Material_Barrier")
                # 3. Right Wing
                write_box("Barrier_RightWing", -t_bar, 0.0, y_s2 + half_a, y_span, -z_span, z_span, "Material_Barrier")
                # 4. Top Block above slits
                write_box("Barrier_TopBlock", -t_bar, 0.0, y_s1 - half_a, y_s2 + half_a, slit_h / 2.0, z_span, "Material_Barrier")
                # 5. Bottom Block below slits
                write_box("Barrier_BottomBlock", -t_bar, 0.0, y_s1 - half_a, y_s2 + half_a, -z_span, -slit_h / 2.0, "Material_Barrier")

                # D. Detector Screen with Texture UV mapping
                f_obj.write("o Detector_Screen\n")
                f_obj.write("usemtl Material_Screen\n")

                # Screen quad vertices at X = L
                f_obj.write(f"v {L:.6f} {-y_span:.6f} {-z_span:.6f}\n") # Bottom-Left
                f_obj.write(f"v {L:.6f} {y_span:.6f} {-z_span:.6f}\n")  # Bottom-Right
                f_obj.write(f"v {L:.6f} {y_span:.6f} {z_span:.6f}\n")   # Top-Right
                f_obj.write(f"v {L:.6f} {-y_span:.6f} {z_span:.6f}\n")  # Top-Left

                # Texture coordinates UV
                f_obj.write("vt 0.0 0.0\n")
                f_obj.write("vt 1.0 0.0\n")
                f_obj.write("vt 1.0 1.0\n")
                f_obj.write("vt 0.0 1.0\n")

                # Face definition linking vertex/texture: f v1/vt1 v2/vt2 v3/vt3 v4/vt4
                b_scr = v_idx
                t_scr = vt_idx
                f_obj.write(f"f {b_scr}/{t_scr} {b_scr+1}/{t_scr+1} {b_scr+2}/{t_scr+2} {b_scr+3}/{t_scr+3}\n\n")
                v_idx += 4
                vt_idx += 4

                # E. 3D Oriented Ray Cylinders (r1 and r2 from slits to screen center)
                write_cylinder("Ray_Path_r1", [0.0, y_s1, 0.0], [L, 0.0, 0.0], r_ray, "Material_Ray1")
                write_cylinder("Ray_Path_r2", [0.0, y_s2, 0.0], [L, 0.0, 0.0], r_ray, "Material_Ray2")

                # F. Which-Way Detectors (if active)
                if which_way_active:
                    det_r = 0.008 * L
                    write_box("Detector_D1", 0.01 * L, 0.03 * L, y_s1 - det_r, y_s1 + det_r, -det_r, det_r, "Material_Detector")
                    write_box("Detector_D2", 0.01 * L, 0.03 * L, y_s2 - det_r, y_s2 + det_r, -det_r, det_r, "Material_Detector")

            return {
                "success": True,
                "message": f"Successfully exported 3D model:\n- {os.path.basename(obj_path)}\n- {os.path.basename(mtl_path)}\n- {texture_filename}"
            }
        except Exception as e:
            return {"success": False, "message": f"3D export error: {str(e)}"}
